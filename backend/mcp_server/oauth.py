"""OAuth 2.1 authorization server for MCP machine clients (ADR 6).

Only the client credentials grant: an MCP client here is another program
acting for itself, not a person signing in, so there is no browser,
redirect or consent step to support. The client proves who it is with the
id and secret from the admin portal and gets back a short lived JWT bound
to the /mcp resource (audience auth.tokens.AUDIENCE_MCP) carrying the
scopes it asked for, limited to the ones it was granted.

Also serves the two discovery documents MCP clients look for:
  - /.well-known/oauth-protected-resource[/mcp] (RFC 9728): which
    authorization server protects /mcp and which scopes exist. The /mcp
    suffixed form is the one the 401 WWW-Authenticate header points at.
  - /.well-known/oauth-authorization-server (RFC 8414): where the token
    endpoint is and which grant and client auth methods it accepts.
Both are written here rather than generated by the SDK, because the SDK
only generates the /mcp suffixed resource document and only inside its
own Starlette app, which mount.py does not serve (see mount.py).

Every token request, successful or not, writes one audit row.
"""

import base64
import binascii
import time
from typing import Optional
from urllib.parse import parse_qsl, unquote

import anyio
from fastapi import APIRouter, Request
from fastapi.responses import JSONResponse

import config
from auth.tokens import AUDIENCE_MCP, issue_token
from mcp_server import clients

router = APIRouter(tags=["mcp-oauth"])

TOKEN_PATH = "/oauth/token"
AUTHORIZE_PATH = "/oauth/authorize"
MCP_PATH = "/mcp"
RESOURCE_METADATA_PATH = "/.well-known/oauth-protected-resource"
AUTH_SERVER_METADATA_PATH = "/.well-known/oauth-authorization-server"

# A token request is a handful of short fields; anything bigger is not
# one, and reading it all would only waste memory.
_MAX_FORM_BYTES = 8 * 1024
_NO_STORE = {"Cache-Control": "no-store", "Pragma": "no-cache"}


def resource_url() -> str:
    return f"{config.PUBLIC_BASE_URL}{MCP_PATH}"


def resource_metadata_url() -> str:
    """RFC 9728 section 3.1: the well known path is inserted between the
    host and the resource path, so the document for /mcp is at
    /.well-known/oauth-protected-resource/mcp. This is the URL the 401
    WWW-Authenticate header carries."""
    return f"{config.PUBLIC_BASE_URL}{RESOURCE_METADATA_PATH}{MCP_PATH}"


def _token_error(status: int, error: str, description: str, extra_headers: Optional[dict] = None) -> JSONResponse:
    headers = dict(_NO_STORE)
    if extra_headers:
        headers.update(extra_headers)
    return JSONResponse({"error": error, "error_description": description}, status_code=status, headers=headers)


def _basic_credentials(header: Optional[str]) -> Optional[tuple[str, str]]:
    """(client_id, secret) from an HTTP Basic header, or None if there is
    no Basic header. RFC 6749 section 2.3.1 says both halves are form url
    encoded before base64, hence the unquote."""
    if not header or not header.lower().startswith("basic "):
        return None
    try:
        decoded = base64.b64decode(header[6:].strip(), validate=True).decode("utf-8")
    except (binascii.Error, UnicodeDecodeError):
        return ("", "")
    client_id, sep, secret = decoded.partition(":")
    if not sep:
        return ("", "")
    return unquote(client_id), unquote(secret)


async def _read_form(request: Request) -> Optional[dict]:
    """Parses an application/x-www-form-urlencoded body without depending
    on python-multipart. None when the body is not a form or is too big.
    A repeated parameter is refused by keeping every value and letting the
    caller see a list (RFC 6749 section 3.2: parameters must not repeat)."""
    content_type = request.headers.get("content-type", "").split(";")[0].strip().lower()
    if content_type != "application/x-www-form-urlencoded":
        return None
    body = b""
    async for chunk in request.stream():
        body += chunk
        if len(body) > _MAX_FORM_BYTES:
            return None
    form: dict = {}
    try:
        pairs = parse_qsl(body.decode("utf-8"), keep_blank_values=True, strict_parsing=False)
    except UnicodeDecodeError:
        return None
    for key, value in pairs:
        if key in form:
            form[key] = [form[key], value] if not isinstance(form[key], list) else form[key] + [value]
        else:
            form[key] = value
    return form


def _audit(actor_id: str, outcome: str, detail: str, started: float, client_pk: Optional[int] = None) -> None:
    clients.record_audit(
        actor_id=actor_id or "unknown",
        action="oauth_token",
        outcome=outcome,
        detail=detail,
        duration_ms=clients.elapsed_ms(started),
        mcp_client_pk=client_pk,
    )


@router.post(TOKEN_PATH)
async def token(request: Request):
    started = time.perf_counter()
    form = await _read_form(request)
    if form is None:
        await anyio.to_thread.run_sync(_audit, "unknown", "error", "invalid_request: not a form body", started)
        return _token_error(400, "invalid_request", "Body must be application/x-www-form-urlencoded")
    repeated = sorted(key for key, value in form.items() if isinstance(value, list))
    if repeated:
        await anyio.to_thread.run_sync(_audit, "unknown", "error", "invalid_request: repeated parameter", started)
        return _token_error(400, "invalid_request", f"Parameter repeated: {', '.join(repeated)}")

    # Client authentication: Basic header or form fields, but not both
    # (RFC 6749 section 2.3: a client must not use more than one method).
    basic = _basic_credentials(request.headers.get("authorization"))
    form_id, form_secret = form.get("client_id"), form.get("client_secret")
    if basic is not None and (form_secret is not None):
        await anyio.to_thread.run_sync(_audit, basic[0] or "unknown", "error", "invalid_request: two auth methods", started)
        return _token_error(400, "invalid_request", "Use either HTTP Basic or client_secret in the body, not both")
    if basic is not None:
        client_id, secret = basic
        if form_id is not None and form_id != client_id:
            await anyio.to_thread.run_sync(_audit, client_id or "unknown", "error", "invalid_request: client_id mismatch", started)
            return _token_error(400, "invalid_request", "client_id in the body does not match HTTP Basic")
    else:
        client_id, secret = form_id or "", form_secret or ""

    grant_type = form.get("grant_type")
    if not grant_type:
        await anyio.to_thread.run_sync(_audit, client_id or "unknown", "error", "invalid_request: no grant_type", started)
        return _token_error(400, "invalid_request", "grant_type is required")

    # Authenticate before looking at the grant, so an unauthenticated
    # caller learns nothing about what this server supports beyond the
    # public metadata. bcrypt is deliberately slow, so it runs on a
    # worker thread, not on the event loop.
    client = await anyio.to_thread.run_sync(clients.authenticate_client, client_id, secret)
    if client is None:
        await anyio.to_thread.run_sync(_audit, client_id or "unknown", "denied", "invalid_client", started)
        return _token_error(
            401,
            "invalid_client",
            "Client authentication failed",
            {"WWW-Authenticate": 'Basic realm="mcp", charset="UTF-8"'},
        )

    if grant_type != "client_credentials":
        await anyio.to_thread.run_sync(
            _audit, client.client_id, "error", "unsupported_grant_type", started, client.id
        )
        return _token_error(400, "unsupported_grant_type", "Only client_credentials is supported")

    # RFC 8707 resource indicator: optional, but if given it must be this
    # server's /mcp, the only resource these tokens are good for.
    resource = form.get("resource")
    if resource is not None and resource.rstrip("/") != resource_url():
        await anyio.to_thread.run_sync(_audit, client.client_id, "error", "invalid_target", started, client.id)
        return _token_error(400, "invalid_target", f"The only resource served here is {resource_url()}")

    granted = set(clients.client_scopes(client))
    requested_raw = form.get("scope")
    if requested_raw is None or not requested_raw.strip():
        scopes = sorted(granted)
    else:
        requested = set(requested_raw.split())
        if not requested <= granted:
            await anyio.to_thread.run_sync(_audit, client.client_id, "denied", "invalid_scope", started, client.id)
            return _token_error(
                400,
                "invalid_scope",
                f"Requested scope exceeds what this client was granted ({' '.join(sorted(granted))})",
            )
        scopes = sorted(requested)

    access_token, expires_at = issue_token(
        subject=client.client_id,
        audience=AUDIENCE_MCP,
        ttl_minutes=config.MCP_TOKEN_MINUTES,
        scopes=scopes,
        extra={"client_id": client.client_id},
    )
    await anyio.to_thread.run_sync(_audit, client.client_id, "ok", f"scope={' '.join(scopes)}", started, client.id)
    print(f"MCP token issued to {client.client_id} in {clients.elapsed_ms(started)} ms")
    return JSONResponse(
        {
            "access_token": access_token,
            "token_type": "Bearer",
            "expires_in": max(0, expires_at - int(time.time())),
            "scope": " ".join(scopes),
        },
        headers=_NO_STORE,
    )


@router.get(AUTHORIZE_PATH)
async def authorize():
    """Exists only so the authorization server metadata can name an
    authorization endpoint: the official MCP Python SDK's metadata model
    (mcp.shared.auth.OAuthMetadata) requires one, and without it the SDK's
    ClientCredentialsOAuthProvider cannot read the metadata at all. No
    interactive flow is offered, so every request is refused with the
    standard error, and response_types_supported below is empty."""
    return _token_error(400, "unsupported_response_type", "Only the client_credentials grant is supported")


def _protected_resource_metadata() -> dict:
    return {
        "resource": resource_url(),
        "authorization_servers": [config.PUBLIC_BASE_URL],
        "scopes_supported": sorted(clients.ALLOWED_SCOPES),
        "bearer_methods_supported": ["header"],
        "resource_name": "SLT Mobitel voice assistant MCP server",
    }


@router.get(RESOURCE_METADATA_PATH)
async def protected_resource_metadata_root():
    return JSONResponse(_protected_resource_metadata())


@router.get(RESOURCE_METADATA_PATH + MCP_PATH)
async def protected_resource_metadata_mcp():
    return JSONResponse(_protected_resource_metadata())


@router.get(AUTH_SERVER_METADATA_PATH)
async def authorization_server_metadata():
    return JSONResponse(
        {
            "issuer": config.PUBLIC_BASE_URL,
            "token_endpoint": f"{config.PUBLIC_BASE_URL}{TOKEN_PATH}",
            "authorization_endpoint": f"{config.PUBLIC_BASE_URL}{AUTHORIZE_PATH}",
            "grant_types_supported": ["client_credentials"],
            "response_types_supported": [],
            "token_endpoint_auth_methods_supported": ["client_secret_basic", "client_secret_post"],
            "scopes_supported": sorted(clients.ALLOWED_SCOPES),
        }
    )
